def build_truth_theta(model: AdditiveComponentModel) -> np.ndarray:
    blocks = []
    for phys, shape in ((BULGE_PHYS, BULGE_SHAPE), (DISK_PHYS, DISK_SHAPE)):
        raw = [to_raw(phys[p], *model.param_bounds[p]) for p in model.sps_param_names]
        blocks.append(
            [
                CENTER,
                CENTER,
                np.log(shape["sigma_y"]),
                np.log(shape["sigma_x"]),
                np.arctanh(shape["rho"]),
                *raw,
            ]
        )
    theta = model.join_theta(jnp.array(blocks, dtype=jnp.float32), jnp.zeros(model.n_shared))
    return np.asarray(theta, dtype=np.float32)


def synthesise_truth_image(
    model: AdditiveComponentModel, emulator: SPSEmulator, convolver: PSFConvolver, theta_true
) -> np.ndarray:
    img = convolver(model.model_image(jnp.asarray(theta_true), emulator, (NPIX, NPIX)))
    return np.asarray(img, dtype=np.float32)


def add_noise(
    true_image: np.ndarray, seed: int, noise_scale: float
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Per-band Gaussian noise with sigma_b = truth(bulge centre)_b / SNR_CENTRE."""
    rng = np.random.default_rng(seed)
    sigma = true_image[:, BULGE_PX[0], BULGE_PX[1]] / SNR_CENTRE * noise_scale
    noise = rng.normal(0.0, 1.0, size=true_image.shape).astype(np.float32) * sigma[:, None, None]
    variance = np.broadcast_to(sigma[:, None, None] ** 2, true_image.shape)
    return (true_image + noise).astype(np.float32), variance.astype(np.float32), sigma


