def run_blind_map(fwd: ForwardModel, quick: bool) -> MAPResult:
    """Blind MAP: data -> image moments -> neutral start -> multistart Adam.

    This function receives ONLY the forward model (which holds the noisy
    observation).  The injected truth is not an argument and is not used
    anywhere in the initialisation or optimisation.
    """
    print("\n--- Blind initialisation + MAP ---")
    t0 = time.perf_counter()
    theta0 = blind_initial_theta(fwd.spatial_model, fwd.observation)
    blocks, _ = fwd.spatial_model.split_theta(theta0)
    mu0 = np.asarray(blocks[:, :2], dtype=np.float64).round(2).tolist()
    sig0 = np.exp(np.asarray(blocks[:, 2:4], dtype=np.float64)).round(2).tolist()
    print(f"  moments start: centres {mu0}, sigmas {sig0} px")
    print(f"  -log_post(blind start, masses unsolved) = {-float(fwd.log_posterior(theta0)):.1f}")
    kwargs = dict(n_rounds=2, steps_per_round=150, final_steps=200) if quick else {}
    print(f"  multistart_map over {len(ARCHETYPES)} archetypes {ARCHETYPES} ...")
    res = multistart_map(fwd, theta0, ARCHETYPES, **kwargs)
    print(
        f"  blind MAP: -log_post = {res.neg_log_posterior:.1f} after {res.n_steps} Adam steps "
        f"per start  [{time.perf_counter() - t0:.0f}s]"
    )
    return res


def run_sampler(fwd: ForwardModel, theta_map: jnp.ndarray, args) -> NUTSResult:
    key = jax.random.PRNGKey(args.seed + 1)
    t0 = time.perf_counter()
    if args.sampler == "nss":
        num_live = 100 if args.quick else args.num_live
        n_out = min(args.n_samples, 300) if args.quick else args.n_samples
        print(
            f"\n--- Nested slice sampling: num_live={num_live}, "
            f"num_inner_steps={args.num_inner_steps or 3 * fwd.spatial_model.n_params}, "
            f"termination={args.termination:g}, n_samples_out={n_out} ---"
        )
        print("  (live points are drawn from the prior; the MAP is not used to start NSS)")
        sampler = NSSSampler(
            fwd,
            num_live=num_live,
            num_inner_steps=args.num_inner_steps,
            termination=args.termination,
            n_samples_out=n_out,
        )
        result = sampler.run(key)
        print(
            f"  logZ = {result.logZ:.2f} +/- {result.logZ_err:.2f}   ESS = {result.ess:.0f}   "
            f"n_steps = {result.n_steps}   n_dead = {result.n_dead}   "
            f"[{time.perf_counter() - t0:.0f}s]"
        )
    else:
        n_warmup = 100 if args.quick else args.n_warmup
        n_samples = 200 if args.quick else args.n_samples
        print(f"\n--- NUTS from the blind MAP: {n_warmup} warmup + {n_samples} samples ---")
        sampler = NUTSSampler(fwd, n_warmup=n_warmup, n_samples=n_samples, max_num_doublings=10)
        result = sampler.run(theta_map, key)
        infos = result.infos
        samples = np.asarray(result.samples)
        moved = float(np.mean(samples.std(axis=0) > 0))
        n_div = int(np.sum(np.asarray(infos.is_divergent)))
        depth = float(np.mean(np.asarray(infos.num_trajectory_expansions)))
        nsteps = float(np.mean(np.asarray(infos.num_integration_steps)))
        print(
            f"  acceptance = {result.acceptance_rate:.3f}   mean tree depth = {depth:.1f} "
            f"(mean {nsteps:.0f} leapfrog steps)   divergences = {n_div}   "
            f"fraction of dims that moved = {moved:.2f}   [{time.perf_counter() - t0:.0f}s]"
        )
    return result


