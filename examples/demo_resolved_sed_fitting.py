def _phys_record(model: AdditiveComponentModel, theta) -> dict:
    d = decode_components(model, jnp.asarray(theta)[None])
    out = {}
    for k, cname in enumerate(["bulge", "disk"]):
        out[cname] = {p: float(d["sps"][0, k, j]) for j, p in enumerate(model.sps_param_names)}
        out[cname + "_shape"] = {n: float(d["shape"][0, k, j]) for j, n in enumerate(SHAPE_NAMES)}
    return out


