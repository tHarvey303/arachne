def decode_components(model: AdditiveComponentModel, thetas: jnp.ndarray) -> dict[str, np.ndarray]:
    """thetas (n, n_params) -> dict of physical per-component arrays.

    ``sps`` (n, K, N_free) holds the per-component free SPS parameters in
    ``model.sps_param_names`` order; ``shape`` (n, K, 5) holds
    ``[mu_y, mu_x, sigma_y, sigma_x, rho]``.
    """
    free_cols = jnp.array([model.emulator_param_names.index(p) for p in model.sps_param_names])

    def one(theta):
        mu, sigma, rho, sps_full = model.component_params(theta)
        shape = jnp.concatenate([mu, sigma, rho[:, None]], axis=1)
        return sps_full[:, free_cols], shape

    sps, shape = jax.vmap(one)(jnp.atleast_2d(thetas))
    return {"sps": np.asarray(sps), "shape": np.asarray(shape)}


def _interval_row(samples_1d: np.ndarray, truth: float) -> tuple[str, bool, bool]:
    q2, q16, q50, q84, q97 = np.percentile(samples_1d, [2.5, 16, 50, 84, 97.5])
    in68 = q16 <= truth <= q84
    in95 = q2 <= truth <= q97
    half = max(0.5 * (q84 - q16), 1e-12)
    dev = abs(q50 - truth) / half
    row = (
        f"truth={truth:8.3f}  median={q50:8.3f}  [{q16:8.3f},{q84:8.3f}]  "
        f"in68={'yes' if in68 else ' no'}  |med-truth|/halfwidth={dev:6.2f}"
    )
    return row, in68, in95


def report_recovery(
    model: AdditiveComponentModel,
    samples_ordered: jnp.ndarray,
    theta_true: np.ndarray,
    theta_map: jnp.ndarray,
) -> dict[str, np.ndarray]:
    print("\n=== Posterior recovery (truth used for grading only) ===")
    post = decode_components(model, samples_ordered)
    tru = decode_components(model, jnp.asarray(theta_true)[None])
    mapd = decode_components(model, jnp.asarray(theta_map)[None])
    names = model.sps_param_names
    n68 = n95 = n_tot = 0
    s68 = s95 = s_tot = 0
    for k, cname in enumerate(COMPONENT_NAMES):
        print(f"\n  {cname}:")
        for j, pname in enumerate(names):
            row, in68, in95 = _interval_row(post["sps"][:, k, j], float(tru["sps"][0, k, j]))
            print(f"    {pname:20s} {row}  MAP={mapd['sps'][0, k, j]:8.3f}")
            n68 += in68
            n95 += in95
            n_tot += 1
        for j, sname in enumerate(SHAPE_NAMES):
            row, in68, in95 = _interval_row(post["shape"][:, k, j], float(tru["shape"][0, k, j]))
            print(f"    {sname:20s} {row}  MAP={mapd['shape'][0, k, j]:8.3f}")
            s68 += in68
            s95 += in95
            s_tot += 1

    mi = model.mass_index
    tot = np.log10(np.sum(10.0 ** post["sps"][:, :, mi], axis=1))
    tot_true = float(np.log10(np.sum(10.0 ** tru["sps"][0, :, mi])))
    row, _, _ = _interval_row(tot, tot_true)
    print(f"\n  total stellar mass  log10 M_tot  {row}")

    print(
        f"\n  Summary: SPS parameters   truth inside 68% interval: {n68}/{n_tot}   "
        f"inside 95%: {n95}/{n_tot}"
    )
    print(
        f"           shape parameters truth inside 68% interval: {s68}/{s_tot}   "
        f"inside 95%: {s95}/{s_tot}"
    )
    print(
        "  Note: with 10-band photometry alone, fesc_lya, dust_bump_amplitude and the "
        "higher-order logsfr_ratio_* are weakly constrained, so wide intervals there are "
        "correct behaviour."
    )
    return {"post": post, "truth": tru, "map": mapd}


def reduced_chi2(fwd: ForwardModel, theta, variance: np.ndarray) -> float:
    """Noise-only reduced chi2 of the PSF-convolved model at theta."""
    model_img = np.asarray(fwd._model_image(jnp.asarray(theta, dtype=jnp.float32)))
    obs = np.asarray(fwd.observation.flux)
    chi2 = np.sum((obs - model_img) ** 2 / variance)
    return float(chi2 / (obs.size - fwd.spatial_model.n_params))


