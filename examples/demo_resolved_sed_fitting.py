#!/usr/bin/env python3
r"""Resolved SED fitting demo: additive bulge + disk, ParrotEmulatorV2, real JWST PSFs.

A two-component galaxy (compact, old, quenched bulge + extended, young, dusty
star-forming disk at a common redshift) is rendered as a 10-band JWST/NIRCam
mock with the real trained ``ParrotEmulatorV2`` checkpoint and real JADES
empirical PSFs, noise is added, and the mock is fitted back **blind** -- the
injected truth is used only to generate the data and to grade the answer,
never to start the fit.

The model
---------
``AdditiveComponentModel`` (``src/arachne/spatial/additive.py``): light is
additive, so each component ``k`` has a unit-sum bivariate Gaussian
surface-brightness profile ``P_k(y, x)`` times the emulator SED ``F_k`` of
its *own* SPS parameters, including its own **total** stellar mass::

    I_b(y, x) = Σ_k F_kb(θ_k) · P_k(y, x)          (K emulator calls per likelihood)

which is then PSF-convolved per band.  ``theta`` is a flat float32 vector of
``K * (5 + 11) = 32`` numbers: per component ``[mu_y, mu_x, log_sigma_y,
log_sigma_x, atanh_rho, sps_raw (11)]`` with every SPS value mapped to its
emulator bounds by a sigmoid.  Redshift is *fixed* at the true value (a bulge
and disk of one galaxy share one redshift; fitting it is not the point here).

The prior is the model's own: uniform in physical space for every SPS
parameter (via the sigmoid Jacobian), the catalogue pipeline's default
Student-t(df=2, scale=0.3) on the ``logsfr_ratio_*`` (the emulator training
grid was drawn from it), Gaussians on the shape parameters.  The
``model_error_frac`` fractional floor in ``GaussianLikelihood`` (default 5%)
is added in quadrature to the photon noise: the emulator is only accurate to
a few per cent and a resolved fit sums ~2.5e5 pixels, so without the floor
the posterior would be far narrower than the emulator's own systematics.

The blind pipeline
------------------
1. ``blind_initial_theta``: centroid + rms size from the S/N-stacked image;
   two components on a size ladder (0.4x, 1.5x the moment size); generic
   neutral SPS values.
2. ``multistart_map``: ``find_map`` (Adam with the K masses re-solved by
   weighted linear least squares between rounds) from the neutral start and
   from a few generic archetypes (low/high dust, rising SFH); the best
   ``-log_posterior`` wins.  ``-log_post(MAP)`` is compared with
   ``-log_post(truth)`` *after* the fact, as a check that the true basin was
   found.
3. Sampling: ``--sampler nss`` (default) runs nested slice sampling from the
   prior (no starting point at all; also yields the evidence ``logZ``);
   ``--sampler nuts`` runs NUTS from the MAP.
4. Components are exchangeable; labels are broken by ordering by size
   (compact first) in the MAP and in every posterior sample.

Assumptions
-----------
* Pixel scale 0.03"/px (assumed; the JADES PSF FITS files carry no WCS).
  Only used for figure annotations -- the model works in pixels.
* Noise: Gaussian, per band, with sigma set so that the bulge-centre pixel
  has S/N = 30 in every band (``--noise-scale`` rescales it).  This is not
  a survey depth; it is chosen to make the disk outskirts a few-sigma per
  pixel.
* Truth: bulge total mass 10^10.3 Msun (sigma = 4 px), disk 10^10.6 Msun
  (16 x 10 px, rho = 0.35), co-centred at z = 2.

Known limitations
-----------------
* The mock is generated by the same emulator that fits it, so emulator
  systematics are absent from the data; the 5% floor is therefore a
  conservative choice here and the posterior is honest about photon noise
  only.  On real data emulator error dominates at this S/N.
* Photometry-only constraints on ``fesc_lya``, ``dust_bump_amplitude`` and
  the higher-order ``logsfr_ratio_*`` are weak; wide (prior-like) intervals
  there are the correct answer, not a failure.
* Two co-centred Gaussians is the mock's own family; real galaxies are not.

Usage
-----
    ssh gn004                     # needs a GPU node (see CLAUDE.md)
    python examples/demo_resolved_sed_fitting.py --quick        # smoke run
    python examples/demo_resolved_sed_fitting.py                # NSS, num_live=500
    python examples/demo_resolved_sed_fitting.py --sampler nuts --n-warmup 500 --n-samples 1000

Expected runtimes (H100, gn004; the blind MAP takes ~20-60 s of this)
---------------------------------------------------------------------
* ``--quick`` (num_live=100, 300 samples out):      ~12 min (measured, GPU shared)
* default (num_live=500, 1000 samples out):          ~20 min (measured, GPU alone; ESS ~640)
* ``--num-live 200``:                                ~15 min (interpolated)

Each NS step replaces ``num_live // 10`` points, so the number of steps is
nearly independent of ``num_live`` and the per-step cost grows sub-linearly
on a GPU (the replacements are vectorised); the evidence error scales as
``1/sqrt(num_live)``.  A second job sharing the GPU slows a run several-fold.

Outputs (under ``--outdir``, default ``outputs/demo/resolved_sed_fitting/``)
----------------------------------------------------------------------------
- ``truth.json``       injected truth (raw theta + physical parameters)
- ``map.json``         blind MAP (raw theta + physical parameters, -log_post)
- ``posterior.hdf5``   size-ordered posterior samples (+ logZ for NSS)
- ``figures/truth_model_residual_mosaic.png``
- ``figures/sps_param_maps.png``
- ``figures/sed_bulge_disk.png``
- ``figures/posterior_summary_1d.png``
- ``figures/sampler_diagnostics.png``
- ``figures/component_profiles.png``
"""

