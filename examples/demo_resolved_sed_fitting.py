def main():
    args = parse_args()
    outdir: Path = args.outdir
    figdir = outdir / "figures"
    figdir.mkdir(parents=True, exist_ok=True)
    print(f"JAX backend: {jax.default_backend()}   devices: {jax.devices()}")
    if jax.default_backend() == "cpu":
        print("  WARNING: running on CPU; this demo is meant for a GPU node (see docstring).")
    t_start = time.perf_counter()

    emulator, psf_model = load_emulator_and_psf()
    model = build_spatial_model(emulator)
    convolver = PSFConvolver(psf_model, image_shape=(NPIX, NPIX))
    print(
        f"Spatial model: AdditiveComponentModel K=2, {model.n_params} free params "
        f"({model.n_params_per_component} per component), fixed {model.fixed_params}"
    )

    # ---- truth + mock (the ONLY place theta_true enters the data path) ----
    theta_true = build_truth_theta(model)
    true_image = synthesise_truth_image(model, emulator, convolver, theta_true)
    assert np.all(np.isfinite(true_image)) and true_image.max() > 0
    # FFT convolution leaves ~1e-7 relative roundoff (tiny negatives) in empty corners.
    assert true_image.min() > -1e-4 * true_image.max(), true_image.min()
    flux_noisy, variance, sigma = add_noise(true_image, args.seed, args.noise_scale)
    print_noise_summary(true_image, sigma)
    with open(outdir / "truth.json", "w") as f:
        json.dump(
            {
                "theta_true": theta_true.tolist(),
                "theta_layout": "per component [mu_y, mu_x, log_sigma_y, log_sigma_x, "
                "atanh_rho, sps_raw...]; sps in sps_param_names order",
                "sps_param_names": model.sps_param_names,
                "bulge": BULGE_PHYS,
                "bulge_shape": BULGE_SHAPE,
                "disk": DISK_PHYS,
                "disk_shape": DISK_SHAPE,
                "log_mass_is_component_total": True,
                "redshift": TRUE_REDSHIFT,
                "pixel_scale_arcsec": PIXEL_SCALE,
                "npix": NPIX,
                "band_names": BAND_NAMES,
                "noise_sigma_nJy": sigma.tolist(),
                "snr_centre": SNR_CENTRE * 1.0 / args.noise_scale,
                "model_err_frac": args.model_err_frac,
                "seed": args.seed,
            },
            f,
            indent=2,
        )

    obs = ObservationCube(
        flux=flux_noisy,
        variance=variance,
        mask=np.ones_like(flux_noisy),
        band_names=BAND_NAMES,
        pixel_scale=PIXEL_SCALE,
    )
    fwd = build_forward_model(obs, model, emulator, convolver, args.model_err_frac)
    print(f"Likelihood: Gaussian with model_error_frac = {args.model_err_frac}")

    # ---- blind fit: no truth information from here until the report ----
    map_res = run_blind_map(fwd, args.quick)
    theta_map = map_res.theta
    # Truth-based grading of the MAP (reporting only; the fit is already done).
    nlp_true = -float(fwd.log_posterior(jnp.asarray(theta_true)))
    print(
        f"  check: -log_post(blind MAP) = {map_res.neg_log_posterior:.1f} vs "
        f"-log_post(truth) = {nlp_true:.1f}  "
        f"(MAP - truth = {map_res.neg_log_posterior - nlp_true:+.1f})"
    )
    with open(outdir / "map.json", "w") as f:
        json.dump(
            {
                "theta_map": np.asarray(theta_map).tolist(),
                "neg_log_posterior": map_res.neg_log_posterior,
                "neg_log_posterior_truth": nlp_true,
                "n_steps_per_start": map_res.n_steps,
                "archetypes": ARCHETYPES,
                **_phys_record(model, theta_map),
            },
            f,
            indent=2,
        )

    result = run_sampler(fwd, theta_map, args)

    # ---- break label symmetry: compact component first in every sample ----
    samples_ordered = jax.vmap(model.order_components_by_size)(result.samples)
    result_ordered = dataclasses.replace(result, samples=samples_ordered)
    result_ordered.to_hdf5(outdir / "posterior.hdf5")
    print(f"  Saved posterior: {outdir / 'posterior.hdf5'}")

    # ---- report ----
    dec = report_recovery(model, samples_ordered, theta_true, theta_map)
    theta_median = jnp.median(samples_ordered, axis=0)
    print("\n  Reduced chi2 (photon noise only, N_data - n_params dof):")
    print(f"    truth            {reduced_chi2(fwd, theta_true, variance):.4f}")
    print(f"    blind MAP        {reduced_chi2(fwd, theta_map, variance):.4f}")
    print(f"    posterior median {reduced_chi2(fwd, theta_median, variance):.4f}")
    if isinstance(result, NSSResult):
        print(
            f"  NSS: logZ = {result.logZ:.2f} +/- {result.logZ_err:.2f}, ESS = {result.ess:.0f}, "
            f"n_steps = {result.n_steps}"
        )

    # ---- figures ----
    print("\n--- Figures ---")
    plt = _setup_mpl()
    model_median_image = np.asarray(fwd._model_image(theta_median))
    plot_truth_model_residual(plt, figdir, true_image, flux_noisy, variance, model_median_image)
    plot_sps_param_maps(plt, figdir, model, result_ordered, theta_true)
    plot_sed_bulge_disk(
        plt, figdir, fwd, true_image, flux_noisy, variance, model_median_image, samples_ordered
    )
    plot_posterior_summary_1d(plt, figdir, model, dec)
    plot_sampler_diagnostics(plt, figdir, result, args.sampler)
    plot_component_profiles(plt, figdir, fwd, model, emulator, theta_true, theta_map, sigma)

    print(f"\nAll done in {time.perf_counter() - t_start:.0f}s. Outputs in: {outdir}")


if __name__ == "__main__":
    main()
