def _radial_profile(img: np.ndarray, centre: tuple[float, float], nbins: int = 40):
    yy, xx = np.mgrid[:NPIX, :NPIX]
    r = np.hypot(yy - centre[0], xx - centre[1]).ravel()
    edges = np.linspace(0, NPIX / 2, nbins + 1)
    idx = np.digitize(r, edges) - 1
    ok = (idx >= 0) & (idx < nbins)
    vals = img.ravel()
    mean = np.array([vals[ok & (idx == i)].mean() for i in range(nbins)])
    count = np.array([(ok & (idx == i)).sum() for i in range(nbins)])
    return 0.5 * (edges[1:] + edges[:-1]), mean, count


